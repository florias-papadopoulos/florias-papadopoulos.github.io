/* Toolbox: primitive roots modulo n. Decides whether Z_n^* is cyclic, finds the smallest generator with the test
   g^(phi/q) != 1 for every prime q dividing phi(n), and lists all primitive roots when there are few. */
Calc.tool({
    id: 'primitive-root',
    live: true,
    inputs: [
        { id: 'n', label: 'Modulus $n$', width: 'l', placeholder: '23', min: 2 }
    ],
    examples: [{ n: '23' }, { n: '41' }, { n: '50' }, { n: '15' }, { n: '2^127 - 1' }, { n: '1000003' }],
    run: async function (v, S) {
        var P = Calc.lib.primes, nt = Calc.lib.nt, T = Calc.lib.primes.T, n = v.n;
        var r = await P.factorStep(S, n), fs = r.factors, phi = P.phi(fs);
        var sc = S.step('Does a primitive root exist?');
        sc.p('A primitive root is a $g$ whose powers run through all of $\\mathbb Z_n^*$, that is with order $\\varphi(n)$. Gauss showed this happens exactly for $n = 1, 2, 4, p^k$ and $2p^k$ with $p$ an odd prime.');
        if (!P.cyclic(fs)) {
            var lam = P.lambda(fs);
            sc.check(false, '$' + T(n) + ' = ' + P.tex(fs) + '$ is not of that form');
            sc.p('Indeed the largest order of any element is $\\lambda(' + T(n) + ') = ' + T(lam) + '$, smaller than $\\varphi(' + T(n) + ') = ' + T(phi) + '$.');
            S.result('There is no primitive root modulo $' + T(n) + '$', { copy: 'none' });
            S.note('$\\mathbb Z_{' + T(n) + '}^*$ is not cyclic. Elements of the largest order $\\lambda(n) = ' + T(lam) + '$ still exist.');
            return;
        }
        sc.check(true, '$' + T(n) + (fs.length > 1 || fs[0].e > 1 ? ' = ' + P.tex(fs) : '') + '$ is of that form, so $\\mathbb Z_n^*$ is cyclic');
        if (n === 2n) {
            S.result('The primitive root modulo 2 is $1$', { copy: '1' });
            S.step('The trivial group').p('$\\mathbb Z_2^* = \\{1\\}$, generated by $1$.');
            return;
        }
        var qf = (await P.factorize(phi, S)).factors, qs = qf.map(function (f) { return f.p; });
        var sp = S.step('The prime factors of $\\varphi(n)$');
        sp.math('\\varphi(' + T(n) + ') = ' + T(phi) + ' = ' + P.tex(qf));
        sp.p('The order of $g$ divides $\\varphi(n)$. If it is a proper divisor, it divides $\\varphi(n)/q$ for some prime $q$. So $g$ is a primitive root exactly when');
        sp.math('g^{\\varphi(n)/q} \\not\\equiv 1 \\pmod n \\quad \\text{for } q = ' + qs.map(T).join(', '));
        var rows = [], g = 0n;
        for (var c = 2n; c < n && c < 100000n; c++) {
            if (nt.gcd(c, n) !== 1n) { rows.push(['$' + T(c) + '$'].concat(qs.map(function () { return ''; }), ['not coprime to $n$'])); continue; }
            var vals = qs.map(function (q) { return nt.powmod(c, phi / q, n); });
            var ok = vals.every(function (x) { return x !== 1n; });
            rows.push(['$' + T(c) + '$'].concat(vals.map(function (x) { return x === 1n ? { v: '$1$', hl: true } : '$' + T(x) + '$'; }), [ok ? 'primitive root' : 'no']));
            if (ok) { g = c; break; }
            if (rows.length % 200 === 0) await S.tick();
        }
        if (!g) Calc.fail('No primitive root below 100000 was found (this should not happen).');
        S.step('Try $g = 2, 3, 4, \\dots$').table(['$g$'].concat(qs.map(function (q) { return '$g^{\\varphi/' + T(q) + '}$'; }), ['']), rows, { mono: true, hl: rows.length - 1 });
        S.result('The smallest primitive root modulo $' + T(n) + '$ is $' + T(g) + '$', { copy: String(g) });
        var count = P.phi(qf);
        S.note('There are $\\varphi(\\varphi(n)) = ' + T(count) + '$ primitive roots modulo $' + T(n) + '$.');
        var sa = S.step('All primitive roots');
        sa.p('Every element is $g^k$, and $g^k$ has order $\\varphi(n) / \\gcd(k, \\varphi(n))$. So the primitive roots are the $g^k$ with $\\gcd(k, \\varphi(n)) = 1$, and there are $\\varphi(\\varphi(n)) = ' + T(count) + '$ of them.');
        if (phi <= 2000n) {
            var all = [], x = 1n;
            for (var k = 1n; k <= phi; k++) { x = x * g % n; if (nt.gcd(k, phi) === 1n) all.push(x); }
            all.sort(function (a, b) { return a < b ? -1 : 1; });
            sa.p('Here, sorted: ' + P.mlist(all) + '.');
        }
    }
});
